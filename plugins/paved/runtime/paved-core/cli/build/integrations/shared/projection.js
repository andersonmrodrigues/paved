import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, lstatSync, realpathSync, unlinkSync, renameSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { isAbsolute, join, relative, resolve, sep } from "node:path";
import { loadCanonicalSkills } from "./catalog.js";
import { AGENT_COMMANDS } from "./commands.js";
const capabilities = [
    "context", "skills", "workflows", "tools", "verification", "status", "diagnostics",
    "lifecycle", "command-discovery", "command-invocation", "compatibility",
];
export function metadata(agent, projectRoot) {
    return {
        id: `paved.integration.${agent}`,
        version: "1.0.0",
        target: agent,
        capabilities,
        root: agent === "codex" ? join(projectRoot, ".agents", "skills") : projectRoot,
    };
}
function header(integration) {
    return `<!-- Generated by Paved ${integration.id}@${integration.version}; edit the canonical skill in Paved Core instead. -->\n`;
}
function projectLauncher(agent) {
    return { command: `node ${agent === "codex" ? ".agents/skills/paved-runtime/bootstrap.mjs" : ".claude/paved/bootstrap.mjs"}` };
}
export function renderSkill(skill, headerLine, launcher) {
    const frontmatter = /^---\s*\n[\s\S]*?\n---\s*\n/.exec(skill.body);
    if (frontmatter === null)
        throw new Error(`Canonical skill ${skill.id} is missing frontmatter.`);
    const location = launcher.location === undefined ? "" : ` ${launcher.location}`;
    return `${frontmatter[0]}${headerLine}${skill.body.slice(frontmatter[0].length)}\n\n## Paved integration\n\nUse the project-local Paved contract as the source of truth. Discover state with \`${launcher.command} status --json\`, load only relevant \`.paved/project/\` context, and invoke verification with \`${launcher.command} verify --json\`.${location} Do not edit generated integration files or bypass Paved lifecycle and ownership checks.\n`;
}
export function renderCommand(command, rendering) {
    const location = rendering.launcher.location === undefined ? "" : ` ${rendering.launcher.location}`;
    const cli = `Invoke \`${rendering.launcher.command} ${command.name} --json\` from the repository root, passing the user's command inputs as supported CLI arguments. The launcher loads the pinned project-local runtime and returns the canonical structured result.${location}`;
    const body = [
        rendering.headerLine,
        `# ${rendering.title}`,
        "",
        command.description,
        "",
        `**Input:** ${command.input.description}`,
        `**Output:** ${command.output}`,
        `**Required lifecycle:** ${command.lifecycle.join(", ")}`,
        `**Required context:** ${command.requiredContext.join(", ")}`,
        `**Required capabilities:** ${command.requiredCapabilities.length === 0 ? "none declared" : command.requiredCapabilities.join(", ")}`,
        `**Allowed side effects:** ${command.allowedSideEffects.join(", ")}`,
        "",
        "## Execution contract",
        "",
        `1. ${cli}`,
        "2. Follow the structured result's status, diagnostics, evidence, and next action. Stop when the runtime blocks execution.",
        ...(command.name === "preview" ? [
            "3. Start with `paved preview start <target> --json`, where the target is one Markdown file or a folder whose Markdown files are reviewed together (an epic and its tasks, a plan and its specs). Give the returned URL to the user.",
            "4. Keep the review active: call `paved preview wait <target> <revision> --json`, starting with the revision from `status`, and follow its `next_action`. A timeout means call `wait` again immediately, because comments reach you only while `wait` runs. Each comment names its `document`. For each one: run `paved preview working <target> <comment-id> --json`, edit that document, then run `paved preview resolve <target> <comment-id> --reply \"<what changed>\" --json`. Never resolve before applying the change, and ask in the conversation when a comment needs a fact you do not have.",
            "5. The preview approves nothing. Keep waiting until the user says in the conversation that the review is finished; ask any approval or confirmation there.",
        ] : []),
        ...(["plan", "feature", "fix", "refactor"].includes(command.name) ? [
            "3. Save the plan at `.paved/documents/plans/<run-id>.md`. When the planning phase requests human approval, start `paved preview start .paved/documents/plans/<run-id>.md --json` (or its folder, when the plan comes with specs or tasks) and present its URL. Follow the `paved.preview` review loop without ending your turn: resolve each comment after editing and advance the workflow once after edits so the approval request covers the current plan. When the user approves the plan in the conversation with an explicit yes, run this command with `--run <run-id> --approve --json`; never approve on your own or on an ambiguous reply.",
        ] : []),
        "",
        "## Failure behavior",
        "",
        ...command.failureSemantics.map((item) => `- ${item}`),
        "- If a required ToolImplementation or runtime is unavailable, stop and explain the missing prerequisite. Never infer or execute a command from repository scripts.",
        "- Do not edit human-owned Paved state or bypass lifecycle, ownership, approval, or verification gates.",
        "",
        ...(command.interaction === "conversational" ? [
            "## Conversational contract",
            "",
            `1. Invoke the command. If it returns \`\"status\": \"awaiting_input\"\`, it is waiting on the user.`,
            "2. Present every decision in `decisions[]` to the user: what Paved detected, what",
            "   remains to decide, why it matters, the options, Paved's recommendation and its evidence.",
            "3. Collect the user's answer. Do not answer on their behalf.",
            `4. Resume the same command with \`--answer <decision-id>=<value> --answered-by <identity>\`,`,
            "   repeating `--answer` once per value for a multi-choice decision.",
            "5. Present the result.",
            "",
            "Follow `core.decisions.decisions` for the full interaction protocol and its prohibitions.",
            "",
        ] : []),
    ].join("\n");
    return rendering.frontmatter === undefined
        ? body
        : `---\nname: ${rendering.frontmatter.name}\ndescription: ${rendering.frontmatter.description}\n---\n${body}`;
}
function skillContent(integration, skill) {
    return renderSkill(skill, header(integration), projectLauncher(integration.target));
}
function commandContent(integration, command) {
    return renderCommand(command, {
        headerLine: `<!-- Generated by Paved ${integration.id}@${integration.version}; edit the canonical command contract in Paved Core instead. -->`,
        title: integration.target === "codex" ? `$paved-${command.name}` : `/paved:${command.name}`,
        launcher: projectLauncher(integration.target),
        ...(integration.target === "codex" ? { frontmatter: { name: `paved-${command.name}`, description: command.description } } : {}),
    });
}
export function planProjection(agent, projectRoot, coreRoot) {
    const integration = metadata(agent, projectRoot);
    const pkg = JSON.parse(readFileSync(join(coreRoot, "package.json"), "utf8"));
    const skills = loadCanonicalSkills(coreRoot);
    const files = skills.map((skill) => ({
        relativePath: agent === "codex"
            ? join(skill.name, "SKILL.md")
            : join("skills", skill.name, "SKILL.md"),
        content: skillContent(integration, skill),
    }));
    const bootstrapRoot = agent === "codex" ? "paved-runtime" : join(".claude", "paved");
    files.push({ relativePath: join(bootstrapRoot, "bootstrap.mjs"), content: readFileSync(join(coreRoot, "integrations", "shared", "bootstrap.mjs"), "utf8") });
    files.push({ relativePath: join(bootstrapRoot, "bootstrap.json"), content: `${JSON.stringify({ package: "paved-core", version: pkg.version, _paved_generated: true }, null, 2)}\n` });
    for (const command of AGENT_COMMANDS) {
        files.push({
            relativePath: agent === "codex"
                ? join(`paved-${command.name}`, "SKILL.md")
                : join("skills", `paved-${command.name}`, "SKILL.md"),
            content: commandContent(integration, command),
        });
        if (agent === "claude-code") {
            files.push({
                relativePath: join(".claude", "commands", "paved", `${command.name}.md`),
                content: commandContent(integration, command),
            });
        }
    }
    if (agent === "claude-code") {
        files.unshift({
            relativePath: join(".claude-plugin", "plugin.json"),
            content: `${JSON.stringify({
                name: "paved",
                version: integration.version,
                description: `Paved agent skills. Generated by Paved integration ${integration.id}.`,
                skills: "./skills",
            }, null, 2)}\n`,
        });
    }
    return { integration, files, diagnostics: [] };
}
function atomicWrite(path, content) {
    const temporaryPath = `${path}.paved-tmp`;
    try {
        writeFileSync(temporaryPath, content, { flag: "wx" });
        renameSync(temporaryPath, path);
    }
    catch (error) {
        if (existsSync(temporaryPath))
            rmSync(temporaryPath, { force: true });
        throw error;
    }
}
function safePath(integration, relativePath) {
    const projectRoot = integration.target === "codex"
        ? resolve(integration.root, "..", "..")
        : integration.root;
    const resolvedRoot = realpathSync(projectRoot);
    const consumerRelativePath = integration.target === "codex"
        ? join(".agents", "skills", relativePath)
        : relativePath;
    const candidate = resolve(resolvedRoot, consumerRelativePath);
    const pathFromRoot = relative(resolvedRoot, candidate);
    if (pathFromRoot === ".." || pathFromRoot.startsWith(`..${sep}`) || isAbsolute(pathFromRoot)) {
        throw new Error(`Integration path escapes its root: ${relativePath}`);
    }
    let current = resolvedRoot;
    for (const component of pathFromRoot.split(sep).filter(Boolean)) {
        current = join(current, component);
        try {
            if (lstatSync(current).isSymbolicLink()) {
                throw new Error(`Refusing to traverse symbolic link in integration path: ${current}`);
            }
        }
        catch (error) {
            if (!(error instanceof Error && "code" in error && error.code === "ENOENT"))
                throw error;
        }
    }
    return candidate;
}
function generatedByPaved(path) {
    try {
        const content = readFileSync(path, "utf8");
        if (content.startsWith("<!-- Generated by Paved "))
            return true;
        if (/^---\s*\n[\s\S]*?\n---\s*\n<!-- Generated by Paved /.test(content))
            return true;
        if (path.endsWith("bootstrap.mjs") && content.startsWith("#!/usr/bin/env node\n// Standalone launcher copied with the agent integration."))
            return true;
        if (path.endsWith("bootstrap.json"))
            return JSON.parse(content)._paved_generated === true;
        if (path.endsWith("plugin.json")) {
            const descriptor = JSON.parse(content);
            return descriptor._paved?.generated === true
                || (typeof descriptor.description === "string"
                    && descriptor.description.startsWith("Paved agent skills. Generated by Paved integration "));
        }
        return false;
    }
    catch {
        return false;
    }
}
export function applyProjection(plan) {
    const pending = [];
    let changed = 0;
    let unchanged = 0;
    for (const file of plan.files) {
        const path = safePath(plan.integration, file.relativePath);
        try {
            if (lstatSync(path).isSymbolicLink())
                throw new Error(`Refusing to write through symlink: ${path}`);
            if (readFileSync(path, "utf8") === file.content) {
                unchanged += 1;
                continue;
            }
            if (!generatedByPaved(path))
                throw new Error(`Refusing to overwrite user-owned integration file: ${path}`);
        }
        catch (error) {
            if (!(error instanceof Error && "code" in error && error.code === "ENOENT"))
                throw error;
        }
        pending.push({ file, path });
    }
    for (const { file, path } of pending) {
        mkdirSync(resolve(path, ".."), { recursive: true });
        safePath(plan.integration, file.relativePath);
        try {
            if (lstatSync(path).isSymbolicLink())
                throw new Error(`Refusing to write through symlink: ${path}`);
            if (readFileSync(path, "utf8") === file.content) {
                unchanged += 1;
                continue;
            }
            if (!generatedByPaved(path))
                throw new Error(`Refusing to overwrite user-owned integration file: ${path}`);
        }
        catch (error) {
            if (!(error instanceof Error && "code" in error && error.code === "ENOENT"))
                throw error;
        }
        atomicWrite(path, file.content);
        changed += 1;
    }
    return { changed, unchanged };
}
export function removeProjection(plan) {
    let removed = 0;
    for (const file of plan.files) {
        const path = safePath(plan.integration, file.relativePath);
        if (generatedByPaved(path)) {
            safePath(plan.integration, file.relativePath);
            unlinkSync(path);
            removed += 1;
        }
    }
    if (plan.integration.target === "claude-code") {
        const plugin = safePath(plan.integration, join(".claude-plugin", "plugin.json"));
        if (generatedByPaved(plugin)) {
            safePath(plan.integration, join(".claude-plugin", "plugin.json"));
            unlinkSync(plugin);
        }
    }
    return removed;
}
export function digest(content) {
    return createHash("sha256").update(content).digest("hex");
}
export function projectionPaths(plan) {
    return plan.files.map((file) => safePath(plan.integration, file.relativePath));
}
